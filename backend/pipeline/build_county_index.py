"""Build the US county -> SSURGO areasymbol index (spec 7.3, P16).

SSURGO's own `legend` table is the authoritative mapping between an areasymbol
and a county name. We cache it locally so a custom field only needs a reverse
geocode, not a full-table spatial scan (which took minutes and is not viable).

Usage:  python -m pipeline.build_county_index
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from rootshift.config import CATALOG_DIR
from rootshift.providers.base import http_json

SDA_URL = "https://sdmdataaccess.sc.egov.usda.gov/Tabular/post.rest"
STATES = {"KS": "Kansas", "NE": "Nebraska", "OK": "Oklahoma", "CO": "Colorado"}


def fetch_legends(state_prefix: str) -> list[tuple[str, str]]:
    payload = http_json(
        SDA_URL,
        {
            "query": f"SELECT areasymbol, areaname FROM legend WHERE areasymbol LIKE '{state_prefix}%' ORDER BY areasymbol",
            "format": "JSON+COLUMNNAME",
        },
        timeout=90,
    )
    table = payload.get("Table") or []
    return [(row[0], row[1]) for row in table[1:]]


def main() -> None:
    entries = []
    for prefix, state_name in STATES.items():
        rows = fetch_legends(prefix)
        for areasymbol, areaname in rows:
            county = areaname.split(" County")[0].strip()
            if not county:
                continue
            entries.append(
                {
                    "areasymbol": areasymbol,
                    "state": state_name,
                    "state_code": prefix,
                    "county": county,
                }
            )
        print(f"{prefix}: {len(rows)} areasymbols")

    out = {
        "version": "1.0.0",
        "source": "USDA SSURGO legend table (Soil Data Access)",
        "note": "Generated by pipeline/build_county_index.py; do not edit by hand.",
        "counties": entries,
    }
    path = Path(CATALOG_DIR) / "counties_us.yaml"
    with path.open("w", encoding="utf-8") as fh:
        yaml.safe_dump(out, fh, allow_unicode=True, sort_keys=False)
    print(f"wrote {path} ({len(entries)} counties)")


if __name__ == "__main__":
    main()
